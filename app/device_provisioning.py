from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import Callable, Dict, List, Optional

MAX_DETAILS = 500
"""Business rule: request details are limited to this many characters."""


class DeviceProvisioningStatus(Enum):
    """States of a request. Only SUBMITTED requests can be decided; decisions are final."""

    SUBMITTED = "SUBMITTED"
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"


class DeviceProvisioningError(Exception):
    """Raised when an action breaks a business rule; the message is safe to show to the user."""


@dataclass
class DeviceProvisioning:
    """A IoT request raised by a user and decided by a reviewer."""

    reference: str
    requested_by: str
    details: str
    created_at: datetime
    status: DeviceProvisioningStatus = DeviceProvisioningStatus.SUBMITTED
    decided_by: Optional[str] = None
    decision_note: Optional[str] = None


@dataclass
class DeviceProvisioningService:
    """Submits, approves and rejects requests and keeps an audit trail."""

    clock: Callable[[], datetime] = lambda: datetime.now(timezone.utc)
    _requests: Dict[str, DeviceProvisioning] = field(default_factory=dict)
    _audit: List[str] = field(default_factory=list)
    _sequence: int = 0

    def submit(self, requested_by: str, details: str) -> DeviceProvisioning:
        """Raises a new request and returns it in status SUBMITTED."""
        # Business rule: every request must say who raised it and what is requested.
        if not requested_by or not requested_by.strip():
            raise DeviceProvisioningError("Requester is required")
        if not details or not details.strip():
            raise DeviceProvisioningError("Details are required")
        # Business rule: details are capped to keep requests reviewable.
        if len(details) > MAX_DETAILS:
            raise DeviceProvisioningError(f"Details must be at most {MAX_DETAILS} characters")
        self._sequence += 1
        reference = f"IOT-{self._sequence:06d}"
        request = DeviceProvisioning(reference, requested_by.strip(), details.strip(), self.clock())
        self._requests[reference] = request
        self._log(reference, "SUBMITTED", requested_by)
        return request

    def approve(self, reference: str, reviewer: str) -> DeviceProvisioning:
        """Approves a pending request."""
        request = self._pending(reference)
        self._require_reviewer(reviewer)
        # Business rule: four-eyes approval: the person who raised a request cannot approve it.
        if request.requested_by.lower() == reviewer.strip().lower():
            raise DeviceProvisioningError("Requester cannot approve their own request")
        request.status = DeviceProvisioningStatus.APPROVED
        request.decided_by = reviewer.strip()
        self._log(reference, "APPROVED", reviewer)
        return request

    def reject(self, reference: str, reviewer: str, reason: str) -> DeviceProvisioning:
        """Rejects a pending request; a reason is mandatory."""
        request = self._pending(reference)
        self._require_reviewer(reviewer)
        # Business rule: a rejection must give the requester a reason.
        if not reason or not reason.strip():
            raise DeviceProvisioningError("A reason is required to reject a request")
        request.status = DeviceProvisioningStatus.REJECTED
        request.decided_by = reviewer.strip()
        request.decision_note = reason.strip()
        self._log(reference, "REJECTED", reviewer)
        return request

    def find(self, reference: str) -> DeviceProvisioning:
        """Returns the request or raises if the reference is unknown."""
        request = self._requests.get(reference)
        if request is None:
            raise DeviceProvisioningError(f"Request not found: {reference}")
        return request

    def audit_trail(self) -> List[str]:
        """Every action taken, oldest first, as 'time reference ACTION by user'."""
        return list(self._audit)

    def _pending(self, reference: str) -> DeviceProvisioning:
        request = self.find(reference)
        # Business rule: decisions are final; only SUBMITTED requests can be decided.
        if request.status is not DeviceProvisioningStatus.SUBMITTED:
            raise DeviceProvisioningError(f"Request {reference} is already {request.status.value}")
        return request

    @staticmethod
    def _require_reviewer(reviewer: str) -> None:
        if not reviewer or not reviewer.strip():
            raise DeviceProvisioningError("Reviewer is required")

    def _log(self, reference: str, action: str, user: str) -> None:
        # Business rule: every action is recorded with who did it and when.
        self._audit.append(f"{self.clock().isoformat()} {reference} {action} by {user}")


